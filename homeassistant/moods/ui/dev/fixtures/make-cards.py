"""Writes ui/dev/fixtures/custom-cards.json: custom mood cards as Home Assistant 2026.11.1 renders them.

Each card is the `card` attribute of sensor.moods_custom_<n>, rendered by Home Assistant's own template
engine from the card body that ui/dev/gen-custom.js writes into moods_custom.yaml, with the slot's
helpers set as below. So the fake Home Assistant (fake-ha.js) serves the phones exactly what Home
Assistant would. Nothing here runs a server or touches a real house.

usage (from homeassistant/moods/, the folder that holds ui/ and ha/; offline, from the uv cache):
  uv run -q --offline --python 3.14 --with homeassistant==2026.11.1 python -I ui/dev/fixtures/make-cards.py
"""
import asyncio, json, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, 'ui', 'dev', 'fixtures', 'custom-cards.json')

from homeassistant.core import HomeAssistant
from homeassistant.helpers.template import Template

# the model (tables, options, card bodies) from the generator itself
G = json.loads(subprocess.check_output(['node', '-e', """
const G = require('./ui/dev/gen-custom.js');
const bodies = {};
for (let n = 1; n <= G.SLOTS; n++) bodies[n] = G.cardBody(n);
process.stdout.write(JSON.stringify({ SLOTS: G.SLOTS, STEPS: G.STEPS, ROLES: G.TABLES.ROLES, options: G.options(), bodies }));
"""], cwd=ROOT))

# what each variant's helpers hold (anything not named is as Home Assistant creates it: input_text
# unknown, input_select its first option, input_number its min, input_boolean off)
VARIANTS = {
    'empty': {},
    # slot 1: the two-minute path, switched on
    'reading': {'name': 'Reading', 'on': 'on', 'steps': [('Bedroom lamps', 'Soft white (2700 K)', 40)]},
    'reading_off': {'name': 'Reading', 'on': 'off', 'steps': [('Bedroom lamps', 'Soft white (2700 K)', 40)]},
    # slot 2: a window, a colour, other indoor lights off, the diffuser on, its own card text
    'dusk': {'name': 'Dusk', 'on': 'on', 'tagline': 'Loft amber and low. Diffuser on.', 'glyph': 'Candle', 'colours': 'Dusk rose',
             'window': 'Evenings (17:00 to 23:00)', 'others': 'Turn other indoor lights off', 'scent': 'Diffuser on',
             'steps': [('Loft lamp', 'Amber', 30)]},
    # slot 3: the movie lamp deep red, every other light off, the TV on
    'red': {'name': 'Red room', 'on': 'on', 'glyph': 'Curtain', 'colours': 'Cinema red', 'others': 'Turn every other light off, outdoors too',
            'tv': 'Bedroom TV on', 'fade': 'Slow (10 s)', 'steps': [('Bedroom movie lamp', 'Deep red', 6)]},
    # slot 4: named and switched on, but nothing to do
    'idle': {'name': 'Nothing yet', 'on': 'on'},
}
# which variant each slot has in each set
SETS = {
    'empty': {str(n): 'empty' for n in range(1, G['SLOTS'] + 1)},
    'ready': {'1': 'reading', '2': 'dusk', '3': 'red', '4': 'idle', '5': 'empty', '6': 'empty'},
}
SLOT_OF = {'empty': None, 'reading': 1, 'reading_off': 1, 'dusk': 2, 'red': 3, 'idle': 4}


async def render(n, v):
    hass = HomeAssistant(tempfile.mkdtemp())
    p = 'custom_mood_%d_' % n
    o = G['options']
    S = hass.states.async_set
    # every role has a member except the kitchen (an empty role, as in the example house)
    for label, r in G['ROLES'].items():
        S(r[0], 'off', {'entity_id': [] if 'kitchen' in r[0] else ['light.leaf_' + r[0].split('.')[1]]})
    S('input_text.' + p + 'name', v.get('name', 'unknown'))
    S('input_text.' + p + 'tagline', v.get('tagline', 'unknown'))
    for k in ('glyph', 'colours', 'window', 'fade', 'others', 'tv', 'scent', 'bed'):
        S('input_select.' + p + k, v.get(k, o[k][0]))
    steps = v.get('steps', [])
    for k in range(1, G['STEPS'] + 1):
        st = steps[k - 1] if k <= len(steps) else (o['step_lights'][0], o['step_do'][0], 1)
        S('input_select.' + p + 'step_%d_lights' % k, st[0])
        S('input_select.' + p + 'step_%d_do' % k, st[1])
        S('input_number.' + p + 'step_%d_pct' % k, str(float(st[2])))
    S('input_boolean.' + p + 'on', v.get('on', 'off'))
    S('input_boolean.' + p + 'night', v.get('night', 'off'))
    card = Template(G['bodies'][str(n)] + '\n{{- card }}', hass).async_render()
    state = Template(G['bodies'][str(n)] + '\n{{- card.mood_state }}', hass).async_render()
    await hass.async_stop(force=True)
    card = json.loads(json.dumps(card))
    assert isinstance(card, dict) and card['mood_state'] == state, (n, state)
    return {'state': state, 'card': card}


async def main():
    out = {'_comment': [
        'Generated by ui/dev/fixtures/make-cards.py (Home Assistant 2026.11.1 renders each card from the body in moods_custom.yaml). Do not edit by hand.',
        'variants: <slot>: <name>: the state and card attribute of sensor.moods_custom_<slot>. sets: <set>: <slot>: <variant name>. fake-ha.js serves the set "empty" (day one) unless told otherwise.'
    ], 'variants': {}, 'sets': SETS}
    for n in range(1, G['SLOTS'] + 1):
        out['variants'][str(n)] = {}
        for name, v in VARIANTS.items():
            if SLOT_OF[name] in (None, n):
                out['variants'][str(n)][name] = await render(n, v)
    with open(OUT, 'w') as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print('wrote', os.path.relpath(OUT, ROOT))

asyncio.run(main())
